use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};

use regex::Regex;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());

    generate_resources(&manifest_dir, &out_dir);
    generate_meson_config(&out_dir);

    build_css(&out_dir);
}

fn build_css(out_dir: &Path) {
    let styles_path = PathBuf::from("src/styles");

    println!("cargo:rerun-if-changed={styles_path:#?}");

    let css = grass::from_path(styles_path.join("app.scss"), &grass::Options::default()).unwrap();

    // Output GTK's at-rules. Sass doesn't support custom at-rules, so we wrap
    // them in a string and unwrap them after Sass has done it's thing.

    // GTK colour expressions - these are similar to Sass's colour functions,
    // but they can operate on GTK colour variables.
    let re_gtk_expressions = Regex::new(r#""--gtk-(.+)""#).unwrap();
    // GTK colour variables
    let re_gtk_colours = Regex::new(r#""(@.+)""#).unwrap();

    let css = re_gtk_expressions.replace_all(&css, "$1");
    let css = re_gtk_colours.replace_all(&css, "$1");

    fs::write(out_dir.join("app.css"), &*css).unwrap();
}

fn generate_meson_config(out_dir: &Path) {
    let app_id = env::var("DELFIN_APP_ID").unwrap_or_else(|_| "cafe.avery.Delfin".to_string());
    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".to_string());
    let builddir = out_dir.to_string_lossy();
    let resources_file = out_dir.join("data").join("resources.gresource");

    let contents = format!(
        r#"// Generated by build.rs as a Meson replacement
pub const APP_ID: &str = "{app_id}";
pub const BUILDDIR: &str = "{builddir}";
pub const RESOURCES_FILE: &str = "{resources}";
pub const VERSION: &str = "{version}";
pub const RESOURCES_BYTES: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/data/resources.gresource"));
"#,
        resources = resources_file.to_string_lossy()
    );

    fs::create_dir_all(out_dir).expect("create OUT_DIR");
    fs::write(out_dir.join("meson_config.rs"), contents).expect("write meson_config.rs");
}

fn generate_resources(manifest_dir: &Path, out_dir: &Path) {
    let data_out = out_dir.join("data");
    fs::create_dir_all(&data_out).expect("create data dir");

    // Prepare metainfo and gresource XML by substituting APP_ID
    let app_id = env::var("DELFIN_APP_ID").unwrap_or_else(|_| "cafe.avery.Delfin".to_string());

    let repo_data_dir = manifest_dir
        .parent()
        .expect("crate has a parent directory")
        .join("data");

    let metainfo_tpl = fs::read_to_string(repo_data_dir.join("cafe.avery.Delfin.metainfo.xml.in"))
        .expect("read metainfo template");
    let metainfo = metainfo_tpl.replace("@APP_ID@", &app_id);
    let metainfo_path = data_out.join(format!("{app_id}.metainfo.xml"));
    fs::write(&metainfo_path, metainfo).expect("write metainfo");

    let gresource_tpl =
        fs::read_to_string(repo_data_dir.join("cafe.avery.Delfin.gresource.xml.in"))
            .expect("read gresource template");
    let gresource_xml = gresource_tpl.replace("@APP_ID@", &app_id);
    let gresource_xml_path = data_out.join(format!("{app_id}.gresource.xml"));
    fs::write(&gresource_xml_path, gresource_xml).expect("write gresource xml");

    let gresource_out = data_out.join("resources.gresource");

    let status = Command::new("glib-compile-resources")
        .current_dir(&data_out)
        .args([
            "--generate",
            "--target",
            gresource_out
                .file_name()
                .expect("resources.gresource name")
                .to_str()
                .unwrap(),
            gresource_xml_path
                .file_name()
                .expect("gresource xml name")
                .to_str()
                .unwrap(),
        ])
        .status();

    match status {
        Ok(s) if s.success() => {}
        _ => {
            println!("cargo:warning=Failed to run glib-compile-resources, generating empty bundle");
            fs::write(&gresource_out, []).expect("write empty gresource");
        }
    }
}
